#!/usr/bin/env python3
"""Regenerate Core/CircuitShapes.swift: one outline per Formula 1 circuit, for the calendar minimaps.

    python3 -I Scripts/generate-circuit-shapes.py

Outlines come from MultiViewer's public circuit data (api.multiviewer.app/api/v1/circuits), the same
coordinate frame OpenF1 uses. Each outline is turned by the circuit's published rotation so it faces the
way the official track map does, flipped to screen coordinates (y down), simplified, and scaled so its
longer side is 1000. Circuits are keyed by the circuit name the race calendar (Jolpica) reports.
Circuits MultiViewer has no outline for (new or returning venues) are left out; the app shows a placeholder.
"""
import json, math, sys, urllib.request
from pathlib import Path

# Calendar circuit name -> MultiViewer circuit key. Seasons 2023-2026.
CIRCUITS = {
    "Albert Park Grand Prix Circuit": 10,
    "Circuit of the Americas": 9,
    "Bahrain International Circuit": 63,
    "Baku City Circuit": 144,
    "Circuit de Barcelona-Catalunya": 15,
    "Hungaroring": 4,
    "Autodromo Enzo e Dino Ferrari": 6,
    "Autódromo José Carlos Pace": 14,
    "Jeddah Corniche Circuit": 149,
    "Lusail International Circuit": 150,
    "Marina Bay Street Circuit": 61,
    "Miami International Autodrome": 151,
    "Circuit de Monaco": 22,
    "Autodromo Nazionale di Monza": 39,
    "Red Bull Ring": 19,
    "Autódromo Hermanos Rodríguez": 65,
    "Shanghai International Circuit": 49,
    "Silverstone Circuit": 2,
    "Circuit de Spa-Francorchamps": 7,
    "Suzuka Circuit": 46,
    "Las Vegas Strip Street Circuit": 152,
    "Circuit Gilles Villeneuve": 23,
    "Yas Marina Circuit": 70,
    "Circuit Park Zandvoort": 55,
}

def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": "formula-live-shape-generator"})
    return json.load(urllib.request.urlopen(request, timeout=30))

def simplify(points, tolerance):
    """Ramer–Douglas–Peucker."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    length = math.hypot(x2 - x1, y2 - y1) or 1e-9
    index, worst = 0, 0.0
    for i in range(1, len(points) - 1):
        x, y = points[i]
        distance = abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1) / length
        if distance > worst:
            index, worst = i, distance
    if worst <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[: index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)

def outline(key):
    index = get("https://api.multiviewer.app/api/v1/circuits")[str(key)]
    for year in sorted(index["years"], reverse=True):
        try:
            data = get(f"https://api.multiviewer.app/api/v1/circuits/{key}/{year}")
            break
        except Exception:
            continue
    else:
        raise SystemExit(f"No data for circuit {key}")
    angle = math.radians(data["rotation"])
    cos, sin = math.cos(angle), math.sin(angle)
    # Counter-clockwise (y up), then flip to screen coordinates.
    turned = [(x * cos - y * sin, -(x * sin + y * cos)) for x, y in zip(data["x"], data["y"])]
    min_x, min_y = min(p[0] for p in turned), min(p[1] for p in turned)
    span = max(max(p[0] for p in turned) - min_x, max(p[1] for p in turned) - min_y)
    scaled = [((x - min_x) * 1000 / span, (y - min_y) * 1000 / span) for x, y in turned]
    # The lap is a loop, so simplify it as two open halves split at the point farthest from the start line.
    far = max(range(len(scaled)), key=lambda i: math.hypot(scaled[i][0] - scaled[0][0], scaled[i][1] - scaled[0][1]))
    first = simplify(scaled[: far + 1], 3.0)
    second = simplify(scaled[far:] + [scaled[0]], 3.0)
    simple = first[:-1] + second[:-1]
    # Simplifying can shave a few units off the extremes; fit the box again so the longer side is exactly 1000.
    min_x, min_y = min(p[0] for p in simple), min(p[1] for p in simple)
    span = max(max(p[0] for p in simple) - min_x, max(p[1] for p in simple) - min_y)
    return [(round((x - min_x) * 1000 / span), round((y - min_y) * 1000 / span)) for x, y in simple]

def main():
    root = Path(__file__).resolve().parent.parent
    lines = []
    for name, key in sorted(CIRCUITS.items()):
        points = outline(key)
        encoded = " ".join(f"{x},{y}" for x, y in points)
        lines.append(f'        "{name}": "{encoded}",')
        print(f"{name}: {len(points)} points", file=sys.stderr)
    source = f'''// Generated by Scripts/generate-circuit-shapes.py. Do not edit by hand.
// Outlines: MultiViewer public circuit data, rotated to the official track-map orientation.

enum CircuitShapeData {{
    /// Calendar circuit name -> "x,y x,y ..." in a box whose longer side is 1000, y down.
    static let outlines: [String: String] = [
{chr(10).join(lines)}
    ]
}}
'''
    (root / "Core" / "CircuitShapeData.swift").write_text(source)

main()
