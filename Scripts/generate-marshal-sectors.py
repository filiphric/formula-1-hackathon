#!/usr/bin/env python3
"""Regenerate Core/MarshalSectorData.swift: where each marshal sector starts, per circuit.

    python3 -I Scripts/generate-marshal-sectors.py

Race control flags a numbered marshal sector ("YELLOW IN TRACK SECTOR 7"). OpenF1 does not say where a
sector is, so the position of each sector's start comes from MultiViewer's public circuit data
(api.multiviewer.app/api/v1/circuits), which uses the same coordinate frame as OpenF1's location data
and shares OpenF1's circuit_key. Circuits are keyed by OpenF1's circuit_short_name, the name the live
session reports.

Marshal sector counts change when a circuit is modified, and MultiViewer's newest layout for a circuit
can be old. So each circuit is checked against what race control actually sent in recent sessions: a
circuit is left out when a flagged sector number exceeds the published count, or when the published
sectors are not numbered 1..N. The app then shows the flag as text only for that circuit.
"""
import json, sys, time, urllib.request
from pathlib import Path

YEARS = (2023, 2024, 2025, 2026)
# Sessions per circuit whose flagged sector numbers are compared with the published count.
CHECKED_SESSIONS = 4


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": "formula-live-sector-generator"})
    for attempt in range(8):
        try:
            return json.load(urllib.request.urlopen(request, timeout=30))
        except urllib.error.HTTPError as error:
            if error.code == 404:
                return None
            time.sleep(2 * (attempt + 1))  # rate limited: back off and retry
    raise SystemExit(f"Could not fetch {url}")


def main():
    sessions = []
    for year in YEARS:
        sessions += get(f"https://api.openf1.org/v1/sessions?year={year}") or []
        time.sleep(0.8)
    names, recent = {}, {}
    for s in sorted(sessions, key=lambda s: s["date_start"]):
        names[s["circuit_key"]] = s["circuit_short_name"]
        if s["session_type"] in ("Race", "Qualifying"):
            recent.setdefault(s["circuit_key"], []).append(s["session_key"])

    index = get("https://api.multiviewer.app/api/v1/circuits")
    lines, comments = [], []
    for key, name in sorted(names.items(), key=lambda item: item[1]):
        entry = index.get(str(key))
        if not entry:
            print(f"{name}: no MultiViewer circuit, left out", file=sys.stderr)
            continue
        year = max(entry["years"], key=int)
        data = get(f"https://api.multiviewer.app/api/v1/circuits/{key}/{year}")
        sectors = sorted((data or {}).get("marshalSectors", []), key=lambda s: s["number"])
        if [s["number"] for s in sectors] != list(range(1, len(sectors) + 1)) or len(sectors) < 3:
            print(f"{name}: marshal sectors are not numbered 1..N, left out", file=sys.stderr)
            continue
        seen = 0
        for session_key in recent.get(key, [])[-CHECKED_SESSIONS:]:
            for message in get(f"https://api.openf1.org/v1/race_control?session_key={session_key}") or []:
                if message.get("scope") == "Sector" and isinstance(message.get("sector"), int):
                    seen = max(seen, message["sector"])
            time.sleep(0.8)
        if seen > len(sectors):
            print(f"{name}: race control flagged sector {seen} but {year} layout has {len(sectors)}, left out", file=sys.stderr)
            continue
        encoded = " ".join(f'{round(s["trackPosition"]["x"])},{round(s["trackPosition"]["y"])}' for s in sectors)
        lines.append(f'        "{name}": "{encoded}",')
        comments.append(f"{name}: {len(sectors)} sectors from the {year} layout (highest flagged: {seen})")
        print(comments[-1], file=sys.stderr)

    root = Path(__file__).resolve().parent.parent
    source = f'''// Generated by Scripts/generate-marshal-sectors.py. Do not edit by hand.
// Marshal sector starts: MultiViewer public circuit data, in OpenF1's coordinate frame.

enum MarshalSectorData {{
    /// OpenF1 circuit_short_name -> "x,y x,y ..." where the Nth pair is where marshal sector N starts.
    static let starts: [String: String] = [
{chr(10).join(lines)}
    ]
}}
'''
    (root / "Core" / "MarshalSectorData.swift").write_text(source)


main()
